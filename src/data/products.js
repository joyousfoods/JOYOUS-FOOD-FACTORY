export const getProductBySlug = (slug) => PRODUCTS.find((p) => p.slug === slug) || null;

export const filterProducts = ({ category, q, sort, bestSeller, newArrival, featured } = {}) => {
  let list = [...PRODUCTS];
  if (category && category !== 'all') list = list.filter((p) => p.category === category);
  if (bestSeller) list = list.filter((p) => p.isBestSeller);
  if (newArrival)  list = list.filter((p) => p.isNewArrival);
  if (featured)    list = list.filter((p) => p.isFeatured);
  if (q) {
    const lower = q.toLowerCase();
    list = list.filter((p) =>
      p.name.toLowerCase().includes(lower) ||
      p.flavour?.toLowerCase().includes(lower) ||
      p.shortDescription?.toLowerCase().includes(lower)
    );
  }
  if (sort === 'price_asc')  list.sort((a, b) => a.price - b.price);
  if (sort === 'price_desc') list.sort((a, b) => b.price - a.price);
  if (sort === 'discount')   list.sort((a, b) => (b.mrp - b.price) - (a.mrp - a.price));
  return list;
};
